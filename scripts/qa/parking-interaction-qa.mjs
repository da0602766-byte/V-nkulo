assert.ok(zoom.scroll<=zoom.width+1,JSON.stringify(zoom));results.push({case:'zoom-200-reduced-motion',...zoom,passed:true});
await page.evaluate(()=>document.documentElement.style.zoom='');await page.setViewportSize({width:320,height:430});
const form=page.locator('.parking-v2-booking form');await form.getByLabel('Celular',{exact:true}).fill('47999998888');await form.getByLabel('Placa',{exact:true}).fill('KBD2B34');await form.getByLabel('Marca e modelo',{exact:true}).fill('Modelo QA');await form.getByLabel('Cor',{exact:true}).fill('Branco');
