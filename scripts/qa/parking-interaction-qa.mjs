const available=page.locator('.parking-v2-space.available').first();await available.focus();await page.keyboard.press('Enter');
assert.equal(await available.getAttribute('aria-pressed'),'true');
const code=await available.locator('strong').innerText();
assert.ok((await page.locator('.parking-v2-selection-summary').innerText()).includes(code));
results.push({case:'keyboard-accessible-list',selectedCode:code,passed:true});
await page.getByRole('button',{name:'Mapa',exact:true}).click();
await page.getByRole('button',{name:'Ampliar mapa'}).click();
