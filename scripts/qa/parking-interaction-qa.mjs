const rect=await viewport.boundingBox();
await page.mouse.move(rect.x+rect.width-20,rect.y+55);await page.mouse.down();await page.mouse.move(rect.x+25,rect.y+55,{steps:10});await page.mouse.up();
assert.equal(await available.getAttribute('aria-pressed'),'true');
assert.ok(await viewport.evaluate(node=>node.scrollLeft)>0);
results.push({case:'pan-does-not-select',passed:true});
await context.setOffline(true);await page.getByText('Você está sem conexão',{exact:true}).waitFor();
const confirm=page.getByRole('button',{name:/Solicitar vaga/});assert.ok(await confirm.count()===0 || await confirm.isDisabled());
